"""gen_float_rules.py [inventory functions.tsv] [out.json]: writes tools/build/float_rules.json, the viewer build's float rules (floatxform.py).

The rule applies the console's arithmetic (fused multiply-adds as MWCC emitted them, the inline Gekko square root) to the code the draw runs. The set is derived from
the inventory (the function inventory, a TSV with an in_draw column = reachable from the draw roots) by directory:
  - the engine and library directories the draw runs and the gameplay shares with it: sysdolphin/baselib, melee/{cm,lb,gr,ef,if,gm,mn,vi,ty,db,sfx,pl}
    (gameplay identity, 127 tapes, holds with them: the camera, joint and animation matrices are display state);
  - the fighter and item files that are the draw (ft: ftdrawcommon, ftafterimage, ftparts, ftanim; it: itdraw);
  - not the collision and fighter/item behavior code (melee/mp, lb/lbcollision.c, the rest of ft and it): the gameplay's results come out of those, and they keep the
    arithmetic the production build has (changing them changes the gameplay output; checked: every fighter or item group breaks the identity).
  - not the simulator's own code (src/runtime, src/Runtime, src/platform, src/stubs, src/gx): floatxform.py's `not_in`.
"""
import json
import sys

INV = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('MSL_FUNCTION_INVENTORY', 'functions.tsv')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'float_rules.json')
DIRS = ['sysdolphin/baselib', 'melee/cm', 'melee/lb', 'melee/gr', 'melee/ef', 'melee/if', 'melee/gm', 'melee/mn', 'melee/vi', 'melee/ty', 'melee/db', 'melee/sfx', 'melee/pl']
FILES = ['melee/ft/ftdrawcommon.c', 'melee/ft/ftafterimage.c', 'melee/ft/ftparts.c', 'melee/ft/ftanim.c', 'melee/it/itdraw.c']
NOT = ['melee/lb/lbcollision.c']
names = set()
for i, line in enumerate(open(INV, encoding='utf-8')):
    if i == 0:
        continue
    p = line.rstrip('\n').split('\t')
    if len(p) < 10 or p[8] != '1':
        continue
    f = p[1]
    if f in NOT:
        continue
    if any(f.startswith(d + '/') for d in DIRS) or f in FILES:
        names.add(p[2])
# the draw-only functions of every other file (the gameplay never runs them)
for i, line in enumerate(open(INV, encoding='utf-8')):
    if i == 0:
        continue
    p = line.rstrip('\n').split('\t')
    if len(p) > 9 and p[8] == '1' and p[9] == '0':
        names.add(p[2])
# Effect placement in gameplay files: functions whose retail code fuses (retail_fused.json: the DOL) and whose result only positions an effect or a camera shake, never a
# gameplay value. The effect spawn dispatcher's random offset (spA8.x += 2.0f * r.x * (HSD_Randf() - 0.5f), a fmadds in ftCo_8009F834) moved Marth's hit-spark z by an ulp
# in bot-marth_roy-1071. Gameplay identity (127 tapes) holds with each of them; the production build is unchanged.
EXTRA = ['ftCo_8009F834', 'ftCo_800A229C', 'ftCo_800C0D0C', 'ftCo_DamageIce_Collide', 'ftCo_800C18A8', 'ftCo_800C1E64', 'ftKb_PrSpecialAirN_Coll', 'fn_80106DB0',
         'ftPr_SpecialAirNChargeRelease_Coll', 'shootNeedles', 'ftYs_SpecialAirSLoop_1_Anim', 'ftCo_800C7590', 'fn_800C7DC4', 'ftCo_800C6408', 'ftColl_8007A06C',
         'ftCommon_8007EFC8', 'grOldPupupu_80210D10', 'it_80270E30', 'it_80278800', 'it_802BE2E8', 'itZeldadinfire_UnkMotion1_Anim', 'it_8027BA54']
names.update(EXTRA)
rules = {
    '_doc': [
        "The viewer build's float rules (tools/build/floatxform.py, applied by llvmcc.py); generated by tools/build/gen_float_rules.py from the inventory.",
        "functions: the draw closure (inventory in_draw=1) of the library and engine directories, the draw files of ft and it, and every draw-only function.",
        "functions also lists EXTRA: effect placement inside gameplay files (see the comment in gen_float_rules.py).",
        "files: whole files the rule covers (src/present: the vendored draw code; the shared matrix, quaternion and vector helpers).",
        "not_in: directories of code the simulator wrote itself; its replacements of the game's functions keep their own, already matched arithmetic.",
    ],
    'functions': sorted(names),
    'files': ['src/present/', 'baselib/mtx.c', 'baselib/quatlib.c', 'melee/lb/lbvector.c', 'melee/lb/lbspdisplay.c', 'baselib/jobj.c', 'baselib/aobj.c', 'baselib/fobj.c',
              'baselib/spline.c', 'baselib/robj.c', 'melee/lb/lbanim.c'],
    'exclude': [],
    'not_in': ['src/runtime/', 'src/Runtime/', 'src/platform/', 'src/stubs/', 'src/gx/', 'src/api', 'tools/'],
    'sqrt': True,
    'nosquare': True,
    'same_block': True,
}
json.dump(rules, open(OUT, 'w'), indent=1)
print(len(names), 'functions,', len(rules['files']), 'files ->', OUT)
